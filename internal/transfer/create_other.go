package transfer

import (
	"os"
	"syscall"
)

func createNoSymlinks(path string) (*os.File, error) {
	return os.OpenFile(path, os.O_WRONLY|os.O_CREATE|os.O_TRUNC|syscall.O_NOFOLLOW, 0644)
}
